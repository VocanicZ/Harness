def undeleted(arms):
    """The note for runs whose repo was left behind (`repo_deleted: false`), or None when none was (#578)."""
    left = [(a, r.get("repo")) for a in sorted(arms, key=arm_key) for r in runs_of(arms[a])
            if r.get("repo_deleted") is False]
    if not left:
        return None
    names = ", ".join(f"`{r}`" if isinstance(r, str) and r else f"the {title(a)} repo" for a, r in left)
    return ("**Repos not deleted:** the run's private bench repos were left behind (`repo_deleted: false`): "
            f"{names}. `gh repo delete` failed (usually the gh token lacks the `delete_repo` scope: `gh auth refresh -s delete_repo`); delete them by hand.")


def config_notes(arms):
    """One sentence per arm that recorded `claude_config` (#584): what Claude setup its sessions loaded."""
    out = []
    for a in sorted(arms, key=arm_key):
        c = arms[a].get("claude_config")
        vals = [num(c.get(k)) if isinstance(c, dict) else None for k in ("skills", "plugins", "mcp_servers")]
        if None in vals:
            continue
        sk, pl, mcp = vals
        iso = arms[a].get("isolation")
        if isinstance(iso, dict) and iso.get("config") == "isolated":   # #590: the plain arm's config plus the engine's own
            eng = [len(iso.get(k) or []) for k in ("engine_skills", "engine_plugins")]
            out.append(f"**Claude config:** the {title(a)} arm's sessions ran on the same isolated Claude config as the plain "
                       f"arm, plus only what the Harness engine installs ({eng[0]} skills, {eng[1]} plugins); its front-door "
                       f"init loaded {sk} skills (the CLI's bundled ones included), {pl} plugins and {mcp} MCP servers.")
        elif sk == pl == mcp == 0:
            out.append(f"**Claude config:** the {title(a)} arm's sessions ran isolated; its front-door init loaded no "
                       "skills, plugins or MCP servers.")
        else:
            out.append(f"**Claude config:** the {title(a)} arm's sessions ran on the operator's own Claude setup, not an "
                       f"isolated one: its front-door init loaded {sk} skills, {pl} user plugins and {mcp} MCP servers "
                       "(a new Harness user would not have them).")
    return out


def settings_notes(arms):
    """One line per arm that recorded how it ran (#590): the models and effort the transcripts show, what the arm
    configured (none: the out-of-the-box defaults), the engine commit, the /harness skill version and the CLI."""
    out = []
    for a in sorted(arms, key=arm_key):
        d = arms[a]
        prov, eff, conf = d.get("provenance"), d.get("effort"), d.get("configured")
        if not any(isinstance(x, dict) for x in (prov, eff, conf)):
            continue
        prov = prov if isinstance(prov, dict) else {}

        def val(v):
            return f"`{' '.join(str(v).split())}`" if isinstance(v, str) and v.strip() else NA
        ran = ", ".join(f"{k} ({n})" for k, n in sorted(eff.items())) if isinstance(eff, dict) and eff else NA
        if isinstance(conf, dict):
            asked = f"model {conf.get('model') or 'default'}, effort {conf.get('effort') or 'default'}"
        else:
            asked = NA
        commit = prov.get("engine_commit")
        commit = commit[:12] + (commit[40:] if len(commit) > 40 else "") if isinstance(commit, str) else commit
        out.append(f"**Run settings, {title(a)}:** models {models(d)}; effort by message {ran}; asked for {asked}; "
                   f"engine commit {val(commit)}; `/harness` skill {val(prov.get('skill_version'))}; "
                   f"Claude Code CLI {val(prov.get('cli_version'))}.")
    return out


def arm_notes(arms):
    """The `note` an arm's results JSON carries, shown verbatim (one line) under the table."""
    return [f"**Note, {title(a)}:** {' '.join(str(arms[a]['note']).split())}" for a in sorted(arms, key=arm_key)
            if isinstance(arms[a].get("note"), str) and arms[a]["note"].strip()]


TIME_NOTE = ("Coding and Testing count time inside agent sessions; the rest of Wall time is time outside them "
             "(orchestration, waiting), drawn as its own segment in the figure.")


RUNS_NOTE = ("**Runs:** `n` is the number of runs behind an arm's row (`bench/run.py --runs N`). With `n` above 1 a cell "
             "shows the median and, in brackets, the range (min–max) over those runs, and the figure draws the median "
             "with range whiskers. `n=1` is a single run: agent wall time and cost vary 20–40% between runs, so one run "
             "supports no claim.")


def stopped_notes(arms):
    """One line per arm whose batch of runs stopped early (#591): how many completed, and why."""
    out = []
    for a in sorted(arms, key=arm_key):
        d = arms[a]
        st = d.get("_stopped")
        if "_runs" not in d or not isinstance(st, dict):
            continue
        out.append(f"**Stopped early, {title(a)}:** {n_of(d)} of {d.get('_requested')} runs completed "
                   f"({len(d['_runs'])} started); stopped because {st.get('reason')}: {' '.join(str(st.get('detail')).split())}")
    return out


def fuzz_note(arms):
    """What the Fuzz divergences column counts (#589), once some arm carries it."""
    docs = [arms[a] for a in sorted(arms, key=arm_key) if num(arms[a].get("fuzz_cases")) is not None]
    if not docs:
        return []
    seed, digest = docs[0].get("fuzz_seed"), str(docs[0].get("fuzz_hash") or "")[:12]
    return ["**Fuzz divergences:** cases where the arm and the reference implementation "
            "disagree, out of the cases run, for the same random argv and ledger files (dash-led arguments and `--`, "
            "a byte order mark and invalid UTF-8, LF / CRLF / lone CR line endings and form feeds or U+2028 in a note, "
            "stdin or a file, a closed output pipe): on standard output, on whether standard error is empty, on the "
            f"exit status, or on the ledger `add` leaves behind (`bench/fuzz.py`, seed {seed}, generator hash "
            f"`{digest}…`). Up to 10 examples per arm are in its results JSON (`fuzz_examples`)."]


def section(run_id, arms, skipped, fig_ref):
    if not arms:
        return ("No benchmark results are committed yet. The table and figure appear here once a run is "
                "recorded under `bench/results/`.")
    parts = []
    bad = invalid_reasons(arms)
    if bad:
        parts.append("**INVALID RUN: rerun.** An arm's quality scan did not run, which is a host problem and must not "
                     "count against an arm, so this run is not a comparison and its numbers are not published as "
                     "one: " + "; ".join(bad) + ".")
    parts += [f"Generated by `bench/figures.py` from `bench/results/{run_id}/`; re-running it reproduces this "
              "section and the figure byte for byte. Costs are list price; `n/a` is a figure the run did not "
              "produce."]
    if fig_ref:
        parts.append(f"![Benchmark: wall time and list-price cost per arm]({fig_ref})")
    parts.append(table(arms, skipped))
    parts.append(TIME_NOTE)
    parts.append(RUNS_NOTE)
    parts += stopped_notes(arms)
    parts += fuzz_note(arms) + config_notes(arms) + settings_notes(arms) + arm_notes(arms)
    if undeleted(arms):
        parts.append(undeleted(arms))
    return "\n\n".join(parts)


def splice(readme_text, body):
    """README text with the marked region replaced; None when the markers are missing or out of order."""
    b = readme_text.find("<!-- bench:begin")
    c = readme_text.find("-->", b) if b >= 0 else -1
    e = readme_text.find(END, c) if c >= 0 else -1
    if e < 0:
        return None
    return readme_text[:c + 3] + "\n\n" + body + "\n\n" + readme_text[e:]


def read(path):
    try:
        with open(path, encoding="utf-8", newline="") as fh:
            return fh.read()
    except OSError:
        return None


def write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, path)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate the README Benchmark section and figure from bench/results/.")
    ap.add_argument("--results-dir", default=os.path.join(HERE, "results"))
    ap.add_argument("--run-id", help="the run to show (default: the latest)")
    ap.add_argument("--readme", default=os.path.join(ROOT, "README.md"))
    ap.add_argument("--figure", help="the figure file (default: <results-dir>/benchmark.svg)")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when the files are not current")
    a = ap.parse_args(argv)
    fig_path = a.figure or os.path.join(a.results_dir, "benchmark.svg")

    runs = run_dirs(a.results_dir)
    run_id = a.run_id or (runs[-1] if runs else None)
    if a.run_id and a.run_id not in runs:
        print(f"figures.py: no results for run {a.run_id!r} in {a.results_dir}", file=sys.stderr)
        return 2
    arms, skipped = load_run(a.results_dir, run_id) if run_id else ({}, {})
    svg = figure(arms)
    fig_ref = os.path.relpath(fig_path, os.path.dirname(os.path.abspath(a.readme))).replace(os.sep, "/") if svg else None
    new_readme = splice(read(a.readme) or "", section(run_id, arms, skipped, fig_ref))
    if new_readme is None:
        print(f"figures.py: {a.readme} has no '<!-- bench:begin ... -->' ... {END!r} markers", file=sys.stderr)
        return 2

    stale = []
    if svg is not None and read(fig_path) != svg:
        stale.append(fig_path)
    if read(a.readme) != new_readme:
        stale.append(a.readme)
    if a.check:
        for p in stale:
            print(f"figures.py: stale: {p}", file=sys.stderr)
        unreproduced = verify_logs(a.results_dir, run_id, arms) if run_id else []
        for m in unreproduced:
            print(f"figures.py: logs do not reproduce results: {m}", file=sys.stderr)
        inconsistent = verify_aggregates(arms) if run_id else []
        for m in inconsistent:
            print(f"figures.py: aggregate does not match its runs: {m}", file=sys.stderr)
        return 1 if stale or unreproduced or inconsistent else 0
    if svg is not None and fig_path in stale:
        write(fig_path, svg)
    if a.readme in stale:
        write(a.readme, new_readme)
    print("figures.py: " + (", ".join(os.path.relpath(p) for p in stale) + " written" if stale else "already current"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
