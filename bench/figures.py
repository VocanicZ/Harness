#!/usr/bin/env python3
"""bench/figures.py — the README Benchmark section: a table and a figure generated only from
bench/results/ (PRD #345, task #384). Deterministic: the same results give the same bytes, so
re-running reproduces the committed files exactly (`--check` fails when they are stale).

    bench/figures.py                    # latest run in bench/results/ -> bench/results/benchmark.svg + README
    bench/figures.py --run-id ID        # a specific run
    bench/figures.py --check            # write nothing; exit 1 when the figure or README are not current, or an
                                        # arm's committed logs, re-measured, do not reproduce its results JSON

Input: `<results-dir>/<run-id>/<arm>.json` (schema: bench/README.md, written by bench/run.py) and an
optional `<results-dir>/<run-id>/skipped.json`, {"<arm>": "<reason>"}, for arms that were not run; an
`<arm>.json` with `"status": "skipped"` (written by `bench/run.py --optional`) counts the same.
Anything missing renders as "n/a" or a "skipped: <reason>" row, never as an error.
"""
import argparse, html, importlib.util, json, os, sys

sys.dont_write_bytecode = True
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)

BEGIN = "<!-- bench:begin — generated by bench/figures.py from bench/results/; do not edit by hand -->"
END = "<!-- bench:end -->"
ARM_ORDER = ["plain", "harness", "harness-1", "harness-3", "hx"]
OPTIONAL_ARMS = ["harness-3", "hx"]        # shown as a "skipped" row when no results are committed
ARM_TITLES = {"plain": "Plain Claude Code", "harness": "Harness (1 worker)", "harness-1": "Harness (1 worker)",
              "harness-3": "Harness (3 workers)", "hx": "Hx"}
NA = "n/a"


# --- logs reproduce the results (#579) --------------------------------------------------
def verify_logs(results_dir, run_id, arms):
    """[message] for every arm whose committed raw logs, re-measured, do not reproduce its results JSON."""
    spec = importlib.util.spec_from_file_location("bench_run", os.path.join(HERE, "run.py"))
    runner = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(runner)
    fc, st = runner._load("forecast"), runner._load("stats")
    bad = []
    for arm, doc in sorted(arms.items()):
        logs = os.path.join(results_dir, run_id, str(doc.get("logs") or arm + ".logs"))
        if os.path.isdir(logs):
            bad += [f"{arm}: {m}" for m in runner.verify_logs(fc, st, doc, logs)]
    return bad


# --- loading ---------------------------------------------------------------------------
def _load(path):
    try:
        with open(path, encoding="utf-8") as fh:
            d = json.load(fh)
    except (OSError, ValueError):
        return None
    return d if isinstance(d, dict) else None


def arm_key(name):
    return (ARM_ORDER.index(name), name) if name in ARM_ORDER else (len(ARM_ORDER), name)


def run_dirs(results_dir):
    try:
        names = sorted(n for n in os.listdir(results_dir) if os.path.isdir(os.path.join(results_dir, n)))
    except OSError:
        return []
    return [n for n in names if any(f.endswith(".json") for f in os.listdir(os.path.join(results_dir, n)))]


def load_run(results_dir, run_id):
    """({arm: results doc}, {arm: skip reason}) for one run."""
    d = os.path.join(results_dir, run_id)
    arms, skipped, recorded = {}, {}, {}
    for f in sorted(os.listdir(d)):
        if not f.endswith(".json"):
            continue
        doc = _load(os.path.join(d, f))
        if doc is None:
            continue
        if f == "skipped.json":
            skipped = {str(k): " ".join(str(v).split()) for k, v in doc.items()}
        elif doc.get("status") == "skipped":   # bench/run.py --optional: the guard refused the arm (#386)
            recorded[str(doc.get("arm") or f[:-5])] = " ".join(str(doc.get("reason") or "not run").split())
        else:
            arms[str(doc.get("arm") or f[:-5])] = doc
    return arms, {**skipped, **recorded}


# --- formatting ------------------------------------------------------------------------
def num(v):
    return v if isinstance(v, (int, float)) and not isinstance(v, bool) else None


def dur(s):
    s = num(s)
    if s is None:
        return NA
    s = int(round(s))
    if s >= 3600:
        return f"{s // 3600}h {s % 3600 // 60:02d}m"
    if s >= 60:
        return f"{s // 60}m {s % 60:02d}s"
    return f"{s}s"


def tok(n):
    n = num(n)
    if n is None:
        return NA
    for div, suf in ((1e9, "G"), (1e6, "M"), (1e3, "k")):
        if n >= div:
            return f"{n / div:.1f}{suf}"
    return str(int(n))


def usd(v):
    v = num(v)
    return NA if v is None else f"${v:,.2f}"


def pct(v):
    v = num(v)
    return NA if v is None else f"{v:.1f}%"


def cell(text):
    return str(text).replace("|", "\\|").replace("\n", " ")


def title(arm):
    return ARM_TITLES.get(arm, arm)


def tokens_total(doc):
    t = doc.get("tokens")
    if not isinstance(t, dict):
        return None
    vals = [num(t.get(k)) for k in ("input", "output", "cache_read", "cache_write")]
    return None if all(v is None for v in vals) else sum(v or 0 for v in vals)


def tokens_split(doc):
    t = doc.get("tokens") if isinstance(doc.get("tokens"), dict) else {}
    return " / ".join(tok(t.get(k)) for k in ("input", "output", "cache_read", "cache_write"))


def hidden(doc):
    h = doc.get("hidden_tests") if isinstance(doc.get("hidden_tests"), dict) else {}
    p, total = num(h.get("passed")), num(h.get("total"))
    if p is None or total is None:
        return f"{NA} (not graded)"
    return f"{int(p)} / {int(total)}"


def work(doc):
    c = doc.get("counts") if isinstance(doc.get("counts"), dict) else {}
    parts = []
    for key, label in (("issues_closed", "issues"), ("prs_merged", "PRs"), ("commits", "commits")):
        if num(c.get(key)) is not None:
            parts.append(f"{int(c[key])} {label}")
    return ", ".join(parts) or NA


def continues(doc):
    c = doc.get("counts") if isinstance(doc.get("counts"), dict) else {}
    v = num(c.get("continue_replies"))
    return NA if v is None else str(int(v))


def cap_status(doc):
    st = doc.get("status")
    if st == "capped":
        return f"capped: {doc.get('capped') or NA}"
    if st == "ok":
        return "within caps"
    if st == "error":
        return "error"
    return NA


def models(doc):
    m = doc.get("models")
    return ", ".join(sorted(str(k) for k in m)) if isinstance(m, dict) and m else NA


def sonar(doc):
    s = doc.get("sonarqube")
    if not isinstance(s, dict):
        q = doc.get("quality")      # bench/quality.py, #387: "skipped (<reason>)" when the scan could not run
        return q if isinstance(q, str) and q.startswith("skipped") else NA
    bits = []
    for key, label, fmt in (("bugs", "bugs", "{:g}"), ("vulnerabilities", "vulns", "{:g}"),
                            ("code_smells", "smells", "{:g}"), ("maintainability_rating", "maint.", "{}"),
                            ("duplicated_lines_density", "dup", "{:g}%"), ("coverage", "cov", "{:g}%")):
        v = s.get(key)
        if v is not None and not isinstance(v, (dict, list)):
            bits.append(f"{label} {fmt.format(v)}")
    return ", ".join(bits) or NA


# --- table -----------------------------------------------------------------------------
def table(arms, skipped):
    has_sonar = any(isinstance(d.get("sonarqube"), dict) for d in arms.values())
    head = ["Arm", "Cap status", "Wall time", "Coding", "Testing", "Tokens", "in / out / cache read / cache write",
            "List price", "% of weekly window", "Hidden tests passed", "Issues / PRs / commits", "Continue replies",
            "Models"] + (["SonarQube"] if has_sonar else [])
    rows = []
    for arm in sorted(arms, key=arm_key):
        d = arms[arm]
        rows.append([title(arm), cap_status(d), dur(d.get("wall_s")), dur(d.get("coding_s")), dur(d.get("testing_s")),
                     tok(tokens_total(d)), tokens_split(d), usd(d.get("cost_usd")), pct(d.get("weekly_window_pct")),
                     hidden(d), work(d), continues(d), models(d)] + ([sonar(d)] if has_sonar else []))
    ncol = len(head)
    for arm in sorted(set(skipped) | (set(OPTIONAL_ARMS) - set(arms)), key=arm_key):
        if arm in arms:
            continue
        rows.append([title(arm), f"skipped: {skipped.get(arm, 'not run')}"] + [NA] * (ncol - 2))
    lines = ["| " + " | ".join(head) + " |", "|" + "|".join(["---"] * ncol) + "|"]
    lines += ["| " + " | ".join(cell(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


# --- figure ----------------------------------------------------------------------------
C_CODING, C_TESTING, C_WALL, C_COST = "#4c78a8", "#f58518", "#9aa0a6", "#54a24b"
FONT = "DejaVu Sans, Verdana, Arial, sans-serif"


def figure(arms):
    """The time and $ per arm as one SVG string, or None with no arm to draw."""
    names = sorted(arms, key=arm_key)
    if not names:
        return None
    label_w, panel_w, gap, row_h, top = 170, 250, 90, 34, 62
    width = label_w + panel_w + gap + panel_w + 70
    height = top + row_h * len(names) + 24
    x_time, x_cost = label_w, label_w + panel_w + gap
    t_vals = []
    for n in names:
        d = arms[n]
        c, t = num(d.get("coding_s")), num(d.get("testing_s"))
        t_vals.append((c, t, num(d.get("wall_s"))))
    t_max = max([(c or 0) + (t or 0) if (c is not None or t is not None) else (w or 0) for c, t, w in t_vals] + [1])
    c_max = max([num(arms[n].get("cost_usd")) or 0 for n in names] + [0.01])
    out = [f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}" '
           f'font-family="{FONT}" font-size="12">',
           "<title>Benchmark: time and list-price cost per arm</title>",
           f'<rect width="{width}" height="{height}" fill="#ffffff"/>',
           f'<text x="{x_time}" y="22" font-size="13" font-weight="bold" fill="#222222">Wall time</text>',
           f'<text x="{x_cost}" y="22" font-size="13" font-weight="bold" fill="#222222">List-price cost</text>']
    for i, (color, text) in enumerate(((C_CODING, "coding"), (C_TESTING, "testing"), (C_WALL, "not split"))):
        lx = x_time + i * 84
        out.append(f'<rect x="{lx}" y="32" width="10" height="10" fill="{color}"/>'
                   f'<text x="{lx + 14}" y="41" fill="#444444">{text}</text>')
    out.append(f'<rect x="{x_cost}" y="32" width="10" height="10" fill="{C_COST}"/>'
               f'<text x="{x_cost + 14}" y="41" fill="#444444">USD at list price</text>')
    for i, n in enumerate(names):
        d = arms[n]
        y = top + i * row_h
        out.append(f'<text x="{label_w - 10}" y="{y + 17}" text-anchor="end" fill="#222222">'
                   f'{html.escape(title(n), quote=True)}</text>')
        c, t, w = t_vals[i]
        if c is not None or t is not None:
            cw = round((c or 0) / t_max * panel_w, 1)
            tw = round((t or 0) / t_max * panel_w, 1)
            out.append(f'<rect x="{x_time}" y="{y + 4}" width="{cw}" height="18" fill="{C_CODING}"/>'
                       f'<rect x="{round(x_time + cw, 1)}" y="{y + 4}" width="{tw}" height="18" fill="{C_TESTING}"/>')
            end = x_time + cw + tw
        else:
            ww = round((w or 0) / t_max * panel_w, 1)
            out.append(f'<rect x="{x_time}" y="{y + 4}" width="{ww}" height="18" fill="{C_WALL}"/>')
            end = x_time + ww
        out.append(f'<text x="{round(end + 6, 1)}" y="{y + 17}" fill="#222222">{dur(d.get("wall_s"))}</text>')
        cost = num(d.get("cost_usd"))
        if cost is None:
            out.append(f'<text x="{x_cost}" y="{y + 17}" fill="#666666">{NA}</text>')
        else:
            bw = round(cost / c_max * panel_w, 1)
            out.append(f'<rect x="{x_cost}" y="{y + 4}" width="{bw}" height="18" fill="{C_COST}"/>'
                       f'<text x="{round(x_cost + bw + 6, 1)}" y="{y + 17}" fill="#222222">{usd(cost)}</text>')
    out.append("</svg>")
    return "\n".join(out) + "\n"


# --- README section --------------------------------------------------------------------
def undeleted(arms):
    """The note for runs whose repo was left behind (`repo_deleted: false`), or None when none was (#578)."""
    left = [(a, arms[a].get("repo")) for a in sorted(arms, key=arm_key) if arms[a].get("repo_deleted") is False]
    if not left:
        return None
    names = ", ".join(f"`{r}`" if isinstance(r, str) and r else f"the {title(a)} repo" for a, r in left)
    return ("**Repos not deleted:** the run's private bench repos were left behind (`repo_deleted: false`): "
            f"{names}. `gh repo delete` failed (usually the gh token lacks the `delete_repo` scope: `gh auth refresh -s delete_repo`); delete them by hand.")


def section(run_id, arms, skipped, fig_ref):
    if not arms:
        return ("No benchmark results are committed yet. The table and figure appear here once a run is "
                "recorded under `bench/results/`.")
    parts = [f"Generated by `bench/figures.py` from `bench/results/{run_id}/`; re-running it reproduces this "
             "section and the figure byte for byte. Costs are list price; `n/a` is a figure the run did not "
             "produce."]
    if fig_ref:
        parts.append(f"![Benchmark: wall time and list-price cost per arm]({fig_ref})")
    parts.append(table(arms, skipped))
    if undeleted(arms):
        parts.append(undeleted(arms))
    return "\n\n".join(parts)


def splice(readme_text, body):
    """README text with the marked region replaced; None when the markers are missing or out of order."""
    b = readme_text.find("<!-- bench:begin")
    c = readme_text.find("-->", b) if b >= 0 else -1
    e = readme_text.find(END, c) if c >= 0 else -1
    if e < 0:
        return None
    return readme_text[:c + 3] + "\n\n" + body + "\n\n" + readme_text[e:]


def read(path):
    try:
        with open(path, encoding="utf-8", newline="") as fh:
            return fh.read()
    except OSError:
        return None


def write(path, text):
    os.makedirs(os.path.dirname(os.path.abspath(path)), exist_ok=True)
    tmp = path + ".tmp"
    with open(tmp, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)
    os.replace(tmp, path)


def main(argv=None):
    ap = argparse.ArgumentParser(description="Generate the README Benchmark section and figure from bench/results/.")
    ap.add_argument("--results-dir", default=os.path.join(HERE, "results"))
    ap.add_argument("--run-id", help="the run to show (default: the latest)")
    ap.add_argument("--readme", default=os.path.join(ROOT, "README.md"))
    ap.add_argument("--figure", help="the figure file (default: <results-dir>/benchmark.svg)")
    ap.add_argument("--check", action="store_true", help="write nothing; exit 1 when the files are not current")
    a = ap.parse_args(argv)
    fig_path = a.figure or os.path.join(a.results_dir, "benchmark.svg")

    runs = run_dirs(a.results_dir)
    run_id = a.run_id or (runs[-1] if runs else None)
    if a.run_id and a.run_id not in runs:
        print(f"figures.py: no results for run {a.run_id!r} in {a.results_dir}", file=sys.stderr)
        return 2
    arms, skipped = load_run(a.results_dir, run_id) if run_id else ({}, {})
    svg = figure(arms)
    fig_ref = os.path.relpath(fig_path, os.path.dirname(os.path.abspath(a.readme))).replace(os.sep, "/") if svg else None
    new_readme = splice(read(a.readme) or "", section(run_id, arms, skipped, fig_ref))
    if new_readme is None:
        print(f"figures.py: {a.readme} has no '<!-- bench:begin ... -->' ... {END!r} markers", file=sys.stderr)
        return 2

    stale = []
    if svg is not None and read(fig_path) != svg:
        stale.append(fig_path)
    if read(a.readme) != new_readme:
        stale.append(a.readme)
    if a.check:
        for p in stale:
            print(f"figures.py: stale: {p}", file=sys.stderr)
        unreproduced = verify_logs(a.results_dir, run_id, arms) if run_id else []
        for m in unreproduced:
            print(f"figures.py: logs do not reproduce results: {m}", file=sys.stderr)
        return 1 if stale or unreproduced else 0
    if svg is not None and fig_path in stale:
        write(fig_path, svg)
    if a.readme in stale:
        write(a.readme, new_readme)
    print("figures.py: " + (", ".join(os.path.relpath(p) for p in stale) + " written" if stale else "already current"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
