#!/usr/bin/env bash
set -uo pipefail
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
CLI="$HERE/../bin/harness"
assert(){ if eval "$2"; then echo "  ok: $1"; else echo "  FAIL: $1"; exit 1; fi; }
assert "no args prints usage"        "\"$CLI\" 2>&1 | grep -qi usage"
assert "unknown cmd errors"          "! \"$CLI\" bogus >/dev/null 2>&1"
assert "unknown cmd: stdout empty (#951)" "[ -z \"\$(\"$CLI\" bogus 2>/dev/null)\" ]"
assert "unknown cmd: usage on stderr"  "err=\$(\"$CLI\" bogus 2>&1 >/dev/null); grep -q '^usage: harness' <<<\"\$err\""
assert "unknown cmd: exit status 2"    "\"$CLI\" bogus >/dev/null 2>&1; [ \$? -eq 2 ]"
assert "unknown cmd: form feed escaped (#952)"  "err=\$(\"$CLI\" \$'st\\fats x' 2>&1 >/dev/null | head -1); [ \"\$err\" = \"harness: unknown command 'st\\u000cats x'\" ]"
assert "unknown cmd: U+2028 escaped (#952)"     "err=\$(\"$CLI\" \$'st\\xe2\\x80\\xa8ats x' 2>&1 >/dev/null | head -1); [ \"\$err\" = \"harness: unknown command 'st\\u2028ats x'\" ]"
assert "unknown cmd: no raw control bytes (#952)" "! \"$CLI\" \$'a\\fb\\xe2\\x80\\xa8c\\xe2\\x80\\xa9d\\xc2\\x85e' 2>&1 >/dev/null | head -1 | LC_ALL=C grep -q \$'[\\x01-\\x1f\\x7f]\\|\\xe2\\x80\\xa8\\|\\xe2\\x80\\xa9\\|\\xc2\\x85'"
assert "unknown cmd: plain UTF-8 name kept (#952)" "err=\$(\"$CLI\" 'héllo' 2>&1 >/dev/null | head -1); [ \"\$err\" = \"harness: unknown command 'héllo'\" ]"
assert "empty command: exit status 2 (#953)"      "\"$CLI\" '' >/dev/null 2>&1; [ \$? -eq 2 ]"
assert "empty command: stdout empty (#953)"       "[ -z \"\$(\"$CLI\" '' 2>/dev/null)\" ]"
assert "empty command: error + usage on stderr (#953)" "err=\$(\"$CLI\" '' 2>&1 >/dev/null); grep -q \"^harness: unknown command ''\\$\" <<<\"\$err\" && grep -q '^usage: harness' <<<\"\$err\""
assert "empty command: name shown as '' on the first stderr line (#975)" "err=\$(\"$CLI\" '' 2>&1 >/dev/null | head -1); [ \"\$err\" = \"harness: unknown command ''\" ]"
assert "no args still exit 0 with usage on stdout (#953)" "out=\$(\"$CLI\" 2>/dev/null); rc=\$?; [ \$rc -eq 0 ] && grep -q '^usage: harness' <<<\"\$out\""
assert "unknown flag -x: harness: prefix and quoted name (#1004)" "err=\$(\"$CLI\" -x 2>&1 >/dev/null | head -1); [ \"\$err\" = \"harness: unknown command '-x'\" ]"
assert "unknown flag -x: stdout empty" "[ -z \"\$(\"$CLI\" -x 2>/dev/null)\" ]"
assert "--help usage on stdout, exit 0" "out=\$(\"$CLI\" --help 2>/dev/null); rc=\$?; [ \$rc -eq 0 ] && grep -q '^usage: harness' <<<\"\$out\""
assert "help usage on stdout, exit 0"   "out=\$(\"$CLI\" help 2>/dev/null); rc=\$?; [ \$rc -eq 0 ] && grep -q '^usage: harness' <<<\"\$out\""
assert "help lists start/stop/status" "\"$CLI\" help 2>&1 | grep -q start && \"$CLI\" help 2>&1 | grep -q status"
assert "help lists pause"  "\"$CLI\" help 2>&1 | grep -q pause"
assert "help lists resume" "\"$CLI\" help 2>&1 | grep -q resume"
assert "help lists update" "\"$CLI\" help 2>&1 | grep -q update"
assert "help lists setup"  "\"$CLI\" help 2>&1 | grep -q setup"
assert "help lists plan"   "\"$CLI\" help 2>&1 | grep -q plan"
assert "help lists prd"    "\"$CLI\" help 2>&1 | grep -q prd"
assert "help lists issue"  "\"$CLI\" help 2>&1 | grep -q issue"
assert "help lists migrate" "\"$CLI\" help 2>&1 | grep -q migrate"
assert "help lists uninstall" "\"$CLI\" help 2>&1 | grep -q uninstall"
echo "── cli ok"
